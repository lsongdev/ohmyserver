
export function createAPI({request}={}){
  return {
    getSettings:({signal}={})=>request(`/settings`,{signal}),
    getStatus:({signal}={})=>request(`/status`,{signal}),
    updateSettings:settings=>request(`/settings`,{method:'PUT',body:settings}),
    action:action=>request(`/action`,{method:'POST',body:{action}}),
    listProviders:({signal}={})=>request(`/providers`,{signal}),
    createProvider:provider=>request(`/providers`,{method:'POST',body:provider}),
    deleteProvider:id=>request(`/providers/${id}`,{method:'DELETE'}),
    listProviderZones:(id,{signal}={})=>request(`/providers/${id}/zones`,{signal}),
    listProviderRecords:(id,zone)=>request(`/providers/${id}/zones/${encodeURIComponent(zone)}/records`),
    createProviderRecord:(id,zone,record)=>request(`/providers/${id}/zones/${encodeURIComponent(zone)}/records`,{method:'POST',body:record}),
    updateProviderRecord:(id,zone,record)=>request(`/providers/${id}/zones/${encodeURIComponent(zone)}/records/${encodeURIComponent(record.id)}`,{method:'PUT',body:record}),
    deleteProviderRecord:(id,zone,recordID)=>request(`/providers/${id}/zones/${encodeURIComponent(zone)}/records/${encodeURIComponent(recordID)}`,{method:'DELETE'}),
    listZones:({signal}={})=>request(`/zones`,{signal}),
    getZone:id=>request(`/zones/${id}`),
    createZone:zone=>request(`/zones`,{method:'POST',body:zone}),
    updateZone:(id,zone)=>request(`/zones/${id}`,{method:'PUT',body:zone}),
    deleteZone:id=>request(`/zones/${id}`,{method:'DELETE'}),
    listRecords:zoneID=>request(`/zones/${zoneID}/records`),
    createRecord:(zoneID,record)=>request(`/zones/${zoneID}/records`,{method:'POST',body:record}),
    updateRecord:(id,record)=>request(`/records/${id}`,{method:'PUT',body:record}),
    deleteRecord:id=>request(`/records/${id}`,{method:'DELETE'}),
    listSubscriptions:({signal}={})=>request(`/subscriptions`,{signal}),
    createSubscription:item=>request(`/subscriptions`,{method:'POST',body:item}),
    updateSubscription:(id,item)=>request(`/subscriptions/${id}`,{method:'PUT',body:item}),
    subscriptionAction:(id,action)=>request(`/subscriptions/${id}/actions/${action}`,{method:'POST'}),
    listRules:({signal}={})=>request(`/rules`,{signal}),
    createRule:rule=>request(`/rules`,{method:'POST',body:{rule}}),
    ruleAction:(id,action)=>request(`/rules/${id}/actions/${action}`,{method:'POST'}),
  };
}
